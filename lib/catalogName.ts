// Полное название варианта: название товара из фида и в скобках свойства варианта через «/»
// («Брюки палаццо (Черный/S)»). Нет свойств или подпись уже есть в названии: просто название.
// Отдельный файл без серверных зависимостей, чтобы им пользовались и серверные страницы, и клиентские компоненты.
export function catalogFullName(name: string, label: string | null | undefined): string {
  const l = (label ?? "").trim();
  if (!l || name.includes(`(${l})`)) return name;
  return `${name} (${l})`;
}

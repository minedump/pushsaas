--  0016 — ID сообщения у провайдера, для проверки статуса доставки.
--
--  Bytehand (SMS) отдаёт id при отправке и позволяет опросить его позже
--  (GET /v2/sms/messages/{id}) — реальный статус ("delivered"/"failed"/…),
--  а не просто "запрос принят". Раньше мы проверяли только успех самой
--  отправки — если Bytehand потом не смог доставить (баланс, блокировка,
--  невалидный номер и т.п.), пользователь молча зависал на экране ввода
--  кода, который никогда не придёт. Экран кода теперь опрашивает статус и
--  уводит обратно в магазин при реальном провале — см. auth/route.ts.
-- =====================================================================

alter table public.otp_requests add column if not exists provider_message_id text;

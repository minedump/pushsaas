-- Снимок контекста и итогового содержимого на момент КАЖДОЙ реальной
-- отправки (campaign_recipients, миграция 0023) — раньше история хранила
-- только статус доставки, восстановить, что именно ушло конкретному
-- получателю, было нельзя (шаблон/фид меняются со временем).
--
-- raw_context — три Liquid-неймспейса ДО резолва по доп. источникам (фид
-- товаров/категорий/коллекций), см. lib/sender.ts splitTemplateData:
--   { template: {...}, context: {...}, automation: {...} }
-- ровно так, как описано в ContextDocs.tsx — сырой контекст шаблона,
-- контекст рассылки/автоматизации и полученный по api/триггеру/событию
-- payload, каждый отдельно, без резолва.
--
-- rendered_content — итоговое отрендеренное содержимое, которое реально
-- ушло получателю (title/body/url/... для push, body для sms,
-- subject/html для email) — снимок, а не пересчёт по сохранённому
-- контексту: автоматизации берут текст шаблона заново на момент отправки
-- (не замораживают его), поэтому более поздняя правка шаблона сделала бы
-- пересчёт задним числом неточным.
alter table public.campaign_recipients add column if not exists raw_context jsonb;
alter table public.campaign_recipients add column if not exists rendered_content jsonb;

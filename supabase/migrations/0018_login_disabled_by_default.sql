-- =====================================================================
--  0018 — Вход по телефону больше не включён автоматически при создании.
--
--  oidc_clients.is_enabled раньше был default true — реальные покупатели
--  могли попасть на страницу входа сразу после клика «Включить вход по
--  телефону», ещё до того, как в проекте настроен хоть один канал с кодом
--  (email/telegram/sms), и упереться в тупик. Теперь включение — отдельное
--  явное действие админа (см. AuthSettings.tsx, «Статус входа»),
--  заблокированное на бэкенде, пока не готов хотя бы один рабочий канал.
--
--  Меняет только DEFAULT для новых строк — уже существующие проекты с
--  is_enabled=true этим не трогает.
-- =====================================================================

alter table public.oidc_clients alter column is_enabled set default false;

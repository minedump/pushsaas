-- Отдельный вебхук-токен для атрибуции заказов — НЕ api_keys (тот даёт
-- широкий доступ к отправке пушей/SMS/email, тут же нужен узкий токен
-- только для одного вебхука). Генерируется автоматически при первом
-- открытии Настроек (см. lib/attribution.ts ensureAttributionToken) —
-- пользователю не нужно ничего "создавать", он уже готов. Хранится
-- плейнтекстом, как остальные provider-токены в project_secrets
-- (Подключения) — это секрет для копирования в вебхук магазина, а не
-- предъявительский ключ с широкими правами, который нужно прятать даже от
-- владельца проекта.
alter table public.project_secrets add column if not exists attribution_token text;
